// POSIX poll remains a Kadre helper because it belongs to ffi:posix, not X11.
private val pollCaptureErrno = Linker.Option.captureCallState("errno")
private val pollCaptureLayout = Linker.Option.captureStateLayout()
private val pollErrnoOffset = pollCaptureLayout.byteOffset(groupElement("errno"))
private val nativePoll: MethodHandle? by lazy {
    PosixSymbols.find("poll")?.let { symbol ->
        linker.downcallHandle(
            symbol,
            FunctionDescriptor.of(
                ValueLayout.JAVA_INT,
                ValueLayout.ADDRESS,
                ValueLayout.JAVA_LONG,
                ValueLayout.JAVA_INT,
            ),
            pollCaptureErrno,
        )
    }
}

data class X11NativePollResult(val value: Int, val errno: Int?)

fun invokeX11NativePoll(
    pollFds: MemorySegment,
    count: Long,
    timeoutMillis: Int,
): X11NativePollResult = Arena.ofConfined().use { arena ->
    val poll = nativePoll ?: error("required POSIX symbol 'poll' is unavailable")
    val callState = arena.allocate(pollCaptureLayout)
    val result = poll.invokeExact(callState, pollFds, count, timeoutMillis) as Int
    X11NativePollResult(
        value = result,
        errno = if (result < 0) callState.get(ValueLayout.JAVA_INT, pollErrnoOffset) else null,
    )
}

// Values exposed by Xlib.h and cursorfont.h are read from the generated binding.
private fun generatedConstant(name: String): Any? = try {
    generatedClass.methods.firstOrNull { it.name == name }?.invoke(null)
        ?: constantsClass.methods.first { it.name == name }.invoke(null)
} catch (_: Throwable) {
    null
}

