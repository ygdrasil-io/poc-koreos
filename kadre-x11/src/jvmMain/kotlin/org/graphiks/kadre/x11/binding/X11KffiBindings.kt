/**
 * Resolves a function from the generated kffi-x11 facade.
 *
 * kffi-x11 owns the native symbol lookup and ABI descriptors. This small
 * adapter only preserves the nullable MethodHandle API used by Kadre's
 * platform code while the backend is migrated incrementally.
 */
private fun generatedFunction(name: String): MethodHandle? = try {
    val method = generatedClass.methods.single { it.name == name }
    generatedLookup.unreflect(method)
} catch (_: Throwable) {
    null
}

val libX11: SymbolLookup? by lazy {
    try {
        SymbolLookup.libraryLookup("libX11.so.6", Arena.global())
    } catch (_: Throwable) {
        null
    }
}

private val linker: Linker = Linker.nativeLinker()

private fun SymbolLookup?.downcall(name: String, descriptor: FunctionDescriptor): MethodHandle? {
    this ?: return null
    return find(name).map { linker.downcallHandle(it, descriptor) }.orElse(null)
}

private fun SymbolLookup?.downcallVariadic(
    name: String,
    descriptor: FunctionDescriptor,
): MethodHandle? {
    this ?: return null
    return find(name).map {
        linker.downcallHandle(it, descriptor, Linker.Option.firstVariadicArg(1))
    }.orElse(null)
}

